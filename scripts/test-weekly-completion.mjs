import assert from 'node:assert/strict';
import {build} from 'esbuild';
const output=await build({entryPoints:['src/weeklyCompletion.ts'],bundle:true,platform:'node',format:'esm',write:false});
const {weeklyCompletion}=await import('data:text/javascript;base64,'+Buffer.from(output.outputFiles[0].text).toString('base64'));
const uid='test-user', other='other-user';
const initial=weeklyCompletion(1,'Monday',uid,[]);
assert(initial.planned>0);assert.equal(initial.completed,0);assert(initial.future.length>0);
const first=initial.open[0];
const log={id:first.key,user_id:uid,week:first.week,day:first.day,exercise_id:first.exercise.id,set_number:first.setNumber,done:true,deleted_at:null,weight:100,reps:8,rpe:7,updated_at:'2026-11-26T12:00:00Z',completed_at:'2026-11-26T12:00:00Z',dirty:0};
const result=weeklyCompletion(1,'Thursday',uid,[log]);
assert.equal(result.completed,1);assert.equal(result.remaining,initial.planned-1);
assert(!result.open.some(s=>s.key===first.key));
assert.equal(weeklyCompletion(1,'Thursday',uid,[log,log]).completed,1);
assert.equal(weeklyCompletion(1,'Thursday',other,[log]).completed,0);
assert.equal(weeklyCompletion(2,'Thursday',uid,[log]).completed,0);
assert.equal(weeklyCompletion(1,'Thursday',uid,[{...log,deleted_at:'deleted'}]).completed,0);
assert.equal(weeklyCompletion(1,'Thursday',uid,[{...log,done:false,skipped:true}]).skipped.length,1);
assert.equal(weeklyCompletion(1,'Thursday',uid,[{...log,done:false,skipped:false}]).open.some(s=>s.key===first.key),true);
assert.equal(weeklyCompletion(1,'Thursday',uid,[{...log,done:false,skipped:true}]).remaining,initial.planned);
assert.equal(weeklyCompletion(1,'Thursday',uid,[{...log,exercise_id:log.exercise_id+'-warmup'}]).completed,0);
console.log('Weekly completion regression passed: catch-up slot identity, future sets, skip/reopen, account and week isolation, deleted rows and warm-ups.');
